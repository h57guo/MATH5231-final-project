for m in range(0,Num_obs_R1):
  xm_R1.append(rearth*(np.pi/180*(lon_R1_obs[m]-lon0_R1))*np.cos(np.pi/180*lat_R1_obs[m]))
  ym_R1.append(rearth*(lat_R1_obs[m]-lat0_R1)*np.pi/180)

xm_R1_,ym_R1_ = np.meshgrid(xm_R1,ym_R1,indexing='xy')

