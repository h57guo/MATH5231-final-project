# variance of samples that fall into each bin
cf_R1 = np.zeros(nbins)
cf_R1[0] = np.mean(np.diag(C_R1))

for b in range(1,nbins):
  ind_R1 = np.where( (Rdd_R1 > r_R1[b]-0.5*dr) & (Rdd_R1 <= r_R1[b]+0.5*dr))
  if ind_R1[0].size > 0:
    cf_R1[b] = np.mean(C_R1[ind_R1[0],ind_R1[1]])

